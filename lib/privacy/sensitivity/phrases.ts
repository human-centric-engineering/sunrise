/**
 * The phrase list behind core's sensitivity classifier (§130, t-1036).
 *
 * Each category has phrases that mean the text discloses it, and `exclude`
 * cues: phrases that share its words and mean something else ("customer
 * acquisition", "restructure this paragraph", "grievance procedure"). An
 * excluded phrase is blanked out before the category's phrases are matched,
 * so it cannot satisfy one of them.
 *
 * **Phrases are regular-expression source, lower case.** A space matches any
 * run of whitespace or hyphens ("mixed race", "mixed-race"), a space then `?`
 * matches none or any run ("food bank", "foodbank"), and every phrase is
 * matched as whole words. Write no space inside a character class. Keep each one narrow: a phrase list is judged by
 * the corpus gate on precision as much as recall
 * (`tests/unit/lib/privacy/sensitivity/corpus.test.ts`), and a broad word
 * ("confidential", "debt", "charged with") flags ordinary business text.
 *
 * The lists aim at what someone says outright. They miss what is implied;
 * that is the spec's stated limit, not a gap to close here with broader words.
 *
 * @see .context/privacy/llm-privacy-layer.md — *Confidential content*
 */
import type { CoreSensitivityCategory } from '@/lib/privacy/adapters/types';

export interface CategoryPhrases {
  /** Any one of these, as whole words, means the category is disclosed. */
  phrases: readonly string[];
  /** Blanked out before `phrases` are matched. */
  exclude?: readonly string[];
}

/** Pronouns and people a disclosure is usually about. */
const WHO = "(?:my|his|her|their|our|your|a|the|one of (?:my|our) \\w+'?s?)";

/**
 * A person as the subject of "is": "she is", "I'm", "they were". Led by the
 * pronoun, because a bare "is" makes "the background is black" or "payroll is
 * bi weekly" read as a disclosure about someone. A contraction is written with
 * its pronoun because the apostrophe follows a letter, and a phrase must start
 * on a word boundary.
 */
const PERSON = '(?:i|he|she|they|we|you)';
const COPULA = `(?:${PERSON} (?:am|is|are|was|were)|${PERSON}'(?:s|m|re))`;

